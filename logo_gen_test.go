// TestLogoIcons writes the tray's two icons to $MOHO_ICONS when MOHO_ICONS is
// set: go test -run LogoIcons. The app icon itself is assets/icon/AppIcon.icon.
func TestLogoIcons(t *testing.T) {
	dir := os.Getenv("MOHO_ICONS")
	if dir == "" {
		t.Skip("MOHO_ICONS not set")
	}
	for on, name := range map[bool]string{false: "off", true: "on"} {
		if err := os.WriteFile(filepath.Join(dir, "tray-"+name+".png"), trayIcon(on), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// TestMobileLogo writes the logo's vector forms into the Flutter project under
// $MOHO_MOBILE_LOGO; scripts/mobile-brand.sh runs it.
func TestMobileLogo(t *testing.T) {
	root := os.Getenv("MOHO_MOBILE_LOGO")
	if root == "" {
		t.Skip("MOHO_MOBILE_LOGO not set")
	}
	path := logoCurve(t)
	const ink, white = "#FF171615", "#FFFFFFFF"
	// An adaptive icon shows 72 of its 108 dp and may cut to a 66 dp circle.
	// At .27 the line spans what it does on the iOS icon and stays in that circle.
	const mark = .27
	drawables := filepath.Join("android", "app", "src", "main", "res", "drawable")
	files := map[string]string{
		filepath.Join(drawables, "ic_launcher_foreground.xml"): logoVector(path, 108, mark, ink),
		filepath.Join(drawables, "ic_launcher_monochrome.xml"): logoVector(path, 108, mark, white),
		// The status bar and the Quick Settings tile: 20 of 24 dp, line included.
		filepath.Join(drawables, "ic_stat_bowel.xml"): logoVector(path, 24, 20.0/194, white),
		filepath.Join("lib", "ui", "logo_path.dart"):  fmt.Sprintf("// Generated by scripts/mobile-brand.sh from logo.go's line. Do not edit.\n\n/// The logo's center line in a 200 by 200 box, stroked %d wide with round caps.\nconst logoPathData = '%s';\nconst logoPathWidth = %d.0;\n", logoWidth, path, logoWidth),
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(root, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// logoVector is an Android vector drawable of the line in a size by size
// viewport, centered at scale.
func logoVector(path string, size int, scale float64, color string) string {
	at := float64(size)/2 - 100*scale
	return fmt.Sprintf(`<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/mobile-brand.sh from logo.go's line. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="%[1]ddp" android:height="%[1]ddp"
    android:viewportWidth="%[1]d" android:viewportHeight="%[1]d">
    <group android:scaleX="%[2]g" android:scaleY="%[2]g" android:translateX="%[3]g" android:translateY="%[3]g">
        <path android:strokeColor="%[4]s" android:strokeWidth="%[5]d"
            android:strokeLineCap="round" android:strokeLineJoin="round"
            android:pathData="%[6]s"/>
    </group>
</vector>
`, size, math.Round(scale*1e4)/1e4, math.Round(at*1e3)/1e3, color, logoWidth, path)
}

// logoCurve fits Catmull-Rom cubics through every 10th of logoPoints: a path
// short enough for a drawable, within a third of a unit of the line.
func logoCurve(t *testing.T) string {
	const step = 10
	type pt struct{ x, y float64 }
	all := make([]pt, 0, len(logoPoints)/2)
	for i := 0; i+1 < len(logoPoints); i += 2 {
		all = append(all, pt{logoPoints[i], logoPoints[i+1]})
	}
	var knots []pt
	for i := 0; i < len(all); i += step {
		knots = append(knots, all[i])
	}
	if (len(all)-1)%step != 0 {
		knots = append(knots, all[len(all)-1])
	}
	num := func(v float64) string { return strings.TrimSuffix(fmt.Sprintf("%.1f", v), ".0") }
	var b strings.Builder
	fmt.Fprintf(&b, "M%s,%s", num(knots[0].x), num(knots[0].y))
	var curve []pt
	for i := 0; i+1 < len(knots); i++ {
		p0, p1, p2, p3 := knots[max(i-1, 0)], knots[i], knots[i+1], knots[min(i+2, len(knots)-1)]
		c1 := pt{p1.x + (p2.x-p0.x)/6, p1.y + (p2.y-p0.y)/6}
		c2 := pt{p2.x - (p3.x-p1.x)/6, p2.y - (p3.y-p1.y)/6}
		fmt.Fprintf(&b, "C%s,%s %s,%s %s,%s", num(c1.x), num(c1.y), num(c2.x), num(c2.y), num(p2.x), num(p2.y))
		for k := 0; k <= 40; k++ {
			u := float64(k) / 40
			v := 1 - u
			curve = append(curve, pt{
				v*v*v*p1.x + 3*v*v*u*c1.x + 3*v*u*u*c2.x + u*u*u*p2.x,
				v*v*v*p1.y + 3*v*v*u*c1.y + 3*v*u*u*c2.y + u*u*u*p2.y,
			})
		}
	}
	for _, p := range all {
		best := math.Inf(1)
		for _, q := range curve {
			best = math.Min(best, math.Hypot(p.x-q.x, p.y-q.y))
		}
		if best > .34 {
			t.Fatalf("the curve is %.2f units off the line at %v", best, p)
		}
	}
	return b.String()
}
